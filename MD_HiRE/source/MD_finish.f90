SUBROUTINE MD_FINISH
   USE MD_UTILS, ONLY: DEALLOC_COMMONS
   USE HIRE_INTERFACE, ONLY: TERMINATE_HIRE
   USE MD_COMMONS, ONLY: XUNIT, EUNIT, RMSDT, RUNIT, MYUNIT, REXT, TEMPUNIT
   USE EXCHANGES, ONLY: REXUNIT
   WRITE(MYUNIT,*) " md_finish> MD simulation completed"
   CLOSE(XUNIT)
   CLOSE(EUNIT)
   IF (RMSDT) CLOSE(RUNIT)
   IF (REXT) THEN
      CLOSE(REXUNIT)
      CLOSE(TEMPUNIT)
   END IF
   CALL TERMINATE_HIRE()
   CALL DEALLOC_COMMONS()
END SUBROUTINE MD_FINISH